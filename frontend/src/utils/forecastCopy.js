import { rubAmount } from './formatRub'

export function getForecastExplanation(probability, answers, limitCap) {
  if (probability === 'высокая') {
    return 'С твоими доходами шансы отличные. Банки охотно выдают первую карту.'
  }
  if (probability === 'низкая') {
    if (answers.income === 'нет') {
      return 'Для твоего возраста без дохода одобрение сложнее. Попробуй с небольшим лимитом или через 6 месяцев.'
    }
    return 'С такими ответами банк может быть настороже. Попробуй меньший лимит, измени цель в анкете или зайди позже.'
  }
  if (answers.income === 'нет') {
    return `Без официального дохода одобряют реже, но для первой карты с лимитом до ${rubAmount(limitCap)} это реально.`
  }
  if (answers.income === 'фриланс') {
    return `С подработками чаще одобряют стартовую карту. Ориентировочный лимит — до ${rubAmount(limitCap)}; важно гасить долг в льготный период.`
  }
  return `Шансы средние: ориентируйся на лимит до ${rubAmount(limitCap)} и возвращай траты в льготный период — так переплаты по процентам не будет.`
}
